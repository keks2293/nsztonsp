import { AesXts } from '../crypto/aes-ops.mjs';
import { AesEcb } from '../crypto/aes128.js';
import { KeysParser } from '../keys.js';
import crypto from 'crypto';
import fs from 'fs';
const hex = b => (typeof b === 'number') ? b.toString(16) : Buffer.from(b).toString('hex');
const nca = fs.readFileSync('/tmp/merged.nca');
const keys = KeysParser.parse(fs.readFileSync('../static/prod.keys', 'utf8'));
const hdrKey = Buffer.from(keys.header_key, 'hex');
const dec = new AesXts(hdrKey).decrypt(nca.subarray(0,0xC00), 0);
console.log('size', nca.length, hex(nca.length));
console.log('magic', hex(dec.subarray(0x200,0x204)));
console.log('0x204-0x207', hex(dec.subarray(0x204,0x208)));
console.log('size@0x208', hex(dec.subarray(0x208,0x210)));
console.log('titleid', hex(dec.subarray(0x210,0x218)));
console.log('contentIndex', hex(dec.subarray(0x218,0x21C)));
console.log('sdkVer', hex(dec.subarray(0x21C,0x220)));
console.log('0x220', hex(dec.subarray(0x220,0x221)));
console.log('sections:');
for(let i=0;i<4;i++){ const b=0x240+i*0x10; console.log('  ['+i+']', hex(dec.subarray(b,b+0x10))); }
console.log('secHashes:', hex(dec.subarray(0x280,0x2C0)));
console.log('keyArea@0x100:', hex(dec.subarray(0x100,0x140)));
const kak00 = Buffer.from(keys.key_area_key_application_00, 'hex');
const area = dec.subarray(0x100,0x300);
const key = new AesEcb(kak00).decrypt(area.subarray(0,0x20));
console.log('keyArea[0] decrypted (titlekey):', hex(key));
const fsex = dec.subarray(0x400,0x600);
console.log('ExeFS FsHeader[0..0x10]:', hex(fsex.subarray(0,0x10)));
console.log('ExeFS 0x40-0x60:', hex(fsex.subarray(0x40,0x60)));
const fsr = dec.subarray(0x600,0x800);
console.log('RomFS FsHeader[0..0x10]:', hex(fsr.subarray(0,0x10)));
console.log('RomFS 0x40-0x80:', hex(fsr.subarray(0x40,0x80)));
